var color = prompt("Ingrese un color: ");

switch(color) {

    case "amarillo":
        console.log("Tu color es amarillo");
        break;

    case "azul":
        console.log("Tu color es azul");
        break;

    case "rojo":
        console.log("Tu color es rojo");
        break;

    default:
        console.log("EL color ingresado no es válido");
        break;
}