/*
Tipos de variables:
var: se declara una variable sin importar el tipo de datos
let: se declara una variable, utilizar dentro de determinados bloques de codigo
const: se declara una variable constante
*/

var nombre = "Ricardo";
var edad = 30;
var presenteONo = true;
var apellido = "Santana";
var estatura = 1.74;

//muestra en consola el mensaje dado
console.log("Nombre: " + nombre + " " + typeof nombre); //typeof: indica el tipo de dato
console.log("Edad: " + edad + " " + typeof edad);
console.log("Presente: " + presenteONo + " " + typeof presenteONo);
console.log("Apellido: " + apellido + " " + typeof apellido);
console.log("Estatura: " + estatura + " " + typeof estatura);

